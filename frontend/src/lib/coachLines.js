/** Реплика тренера по классу хода. */
export function lineForClass(cls) {
  return say(cls)
}

/** Настроение аватара по классу хода. */
export function moodForClass(cls) {
  if (cls === 'brilliant' || cls === 'best') return 'pleased'
  if (cls === 'inaccuracy' || cls === 'mistake' || cls === 'blunder') return 'skeptical'
  return 'idle'
}
